/* ==========================================================================
   algorithms.js — หัวใจของเกม: อัลกอริทึมการเรียงลำดับ (Sorting Algorithms)
   --------------------------------------------------------------------------
   ทุกอัลกอริทึมเขียนเป็น "Generator" (function*) ที่ yield ออกมาทีละขั้นตอน
   เพื่อให้สนามฝึก (Practice Stepper) นำไปเล่นทีละก้าวหรือเล่นอัตโนมัติ

   รูปแบบของ step ที่ yield ออกมา:
     { type, i, j, arr, sorted, text }
       type   : 'compare' (เปรียบเทียบ) | 'swap' (สลับ) | 'min' (พบค่าน้อยสุดใหม่)
                | 'sorted' (ล็อกตำแหน่งแล้ว) | 'done' (เสร็จสิ้น)
       i, j   : ตำแหน่ง (index) ของหมีที่เกี่ยวข้องกับขั้นตอนนี้
       arr    : ภาพถ่าย (snapshot) ของอาร์เรย์ ณ ขั้นตอนนั้น
       sorted : รายการ index ที่อยู่ในตำแหน่งสุดท้ายถูกต้องแล้ว
       text   : คำอธิบายภาษาไทยของขั้นตอน
   ========================================================================== */

const Algo = (() => {

  /* ฟังก์ชันช่วย: สร้าง step พร้อมคัดลอกอาร์เรย์ (เพื่อไม่ให้ค่าเปลี่ยนตามภายหลัง) */
  function makeStep(type, i, j, a, sorted, text, min = -1) {
    return { type, i, j, arr: a.slice(), sorted: sorted.slice(), text, min };
  }

  /* ------------------------------------------------------------------------
     1) BUBBLE SORT (การเรียงแบบฟองสบู่)
     ------------------------------------------------------------------------
     แนวคิด: เดินจากซ้ายไปขวา เปรียบเทียบ "คู่ที่อยู่ติดกัน" เสมอ
             ถ้าตัวซ้ายมากกว่าตัวขวา -> สลับ
             เมื่อจบ 1 รอบ (pass) ตัวที่มากที่สุดจะ "ลอย" ไปอยู่ท้ายแถวเสมอ
             แล้วรอบถัดไปไม่ต้องดูตำแหน่งท้ายสุดนั้นอีก
     ความซับซ้อนเวลา: เฉลี่ย/แย่สุด O(n²), ดีสุด O(n) (เมื่อเรียงอยู่แล้ว)
  ------------------------------------------------------------------------ */
  function* bubbleSort(input) {
    const a = input.slice();
    const n = a.length;
    const sorted = [];                       // ตำแหน่งที่ล็อกแล้ว (ท้ายแถว)

    for (let pass = 0; pass < n - 1; pass++) {
      let swapped = false;                   // ใช้ตรวจว่ารอบนี้มีการสลับไหม

      // วนเฉพาะส่วนที่ยังไม่ล็อก (ลดลง 1 ตัวทุกรอบ)
      for (let j = 0; j < n - 1 - pass; j++) {
        yield makeStep('compare', j, j + 1, a, sorted,
          `เปรียบเทียบ ${a[j]} กับ ${a[j + 1]} (ตัวที่อยู่ติดกัน)`);

        if (a[j] > a[j + 1]) {               // ตัวซ้ายมากกว่า -> อยู่ผิดที่ ต้องสลับ
          const leftVal = a[j];
          const rightVal = a[j + 1];
          [a[j], a[j + 1]] = [a[j + 1], a[j]];
          swapped = true;
          yield makeStep('swap', j, j + 1, a, sorted,
            `${leftVal} > ${rightVal} จึงสลับที่กัน`);
        }
      }

      sorted.push(n - 1 - pass);             // ตัวท้ายสุดของรอบนี้อยู่ที่ถูกต้องแล้ว
      yield makeStep('sorted', n - 1 - pass, n - 1 - pass, a, sorted,
        `จบรอบที่ ${pass + 1}: ${a[n - 1 - pass]} ลอยไปอยู่ตำแหน่งสุดท้ายแล้ว`);

      if (!swapped) {                        // ไม่มีการสลับเลย = ทุกตัวที่เหลือเรียงถูกต้องแล้ว
        for (let k = 0; k < n - 1 - pass; k++) {
          if (!sorted.includes(k)) sorted.push(k);
        }
        sorted.sort((x, y) => x - y);
        yield makeStep('sorted', -1, -1, a, sorted,
          'ไม่มีการสลับในรอบนี้ แสดงว่าแถวเรียงลำดับถูกต้องทั้งหมดแล้ว');
        break;
      }
    }

    if (!sorted.includes(0)) {
      sorted.push(0);
      sorted.sort((x, y) => x - y);
      yield makeStep('sorted', 0, 0, a, sorted,
        `ตำแหน่งแรกคือ ${a[0]} เข้าที่โดยอัตโนมัติ`);
    }

    for (let k = 0; k < n; k++) {
      if (!sorted.includes(k)) sorted.push(k);
    }
    sorted.sort((x, y) => x - y);
    yield makeStep('done', -1, -1, a, sorted, 'เรียงเสร็จแล้ว!');
  }

  /* ------------------------------------------------------------------------
     2) SELECTION SORT (การเรียงแบบเลือก)
     ------------------------------------------------------------------------
     แนวคิด: แบ่งแถวเป็น 2 ส่วน  [ส่วนที่เรียงแล้ว | ส่วนที่ยังไม่เรียง]
             แต่ละรอบ "กวาดหาตัวที่น้อยที่สุด" ในส่วนที่ยังไม่เรียง
             แล้วสลับมันมาไว้หน้าสุดของส่วนที่ยังไม่เรียง (สลับแค่ 1 ครั้ง/รอบ)
     จุดเด่น: จำนวนการสลับน้อยมาก (อย่างมาก n-1 ครั้ง)
     ความซับซ้อนเวลา: O(n²) ทุกกรณี (ต้องกวาดหาค่าน้อยสุดทุกรอบ)
  ------------------------------------------------------------------------ */
  function* selectionSort(input) {
    const a = input.slice();
    const n = a.length;
    const sorted = [];

    for (let i = 0; i < n - 1; i++) {
      let min = i;                           // สมมติว่าตัวแรกของส่วนที่ยังไม่เรียงน้อยสุด
      yield makeStep('min', min, min, a, sorted,
        `รอบที่ ${i + 1}: เริ่มจากสมมติว่า ${a[min]} น้อยที่สุด`, min);

      for (let j = i + 1; j < n; j++) {      // กวาดหาตัวที่น้อยกว่าในส่วนที่เหลือ
        yield makeStep('compare', min, j, a, sorted,
          `เทียบ ${a[j]} กับค่าน้อยสุดตอนนี้ (${a[min]})`, min);
        if (a[j] < a[min]) {                 // เจอค่าที่น้อยกว่า -> จดตำแหน่งไว้
          min = j;
          yield makeStep('min', min, min, a, sorted,
            `พบ ${a[min]} น้อยกว่า จึงจำเป็นค่าน้อยสุดใหม่`, min);
        }
      }

      if (min !== i) {                       // สลับตัวน้อยสุดมาไว้ตำแหน่ง i (ถ้าไม่ได้อยู่แล้ว)
        const valI = a[i];
        const valMin = a[min];
        [a[i], a[min]] = [a[min], a[i]];
        yield makeStep('swap', i, min, a, sorted,
          `สลับ ${valMin} มาไว้ตำแหน่งที่ ${i + 1} (แทน ${valI})`, min);
      }

      sorted.push(i);                        // ตำแหน่ง i ล็อกแล้ว
      yield makeStep('sorted', i, i, a, sorted,
        `ตำแหน่งที่ ${i + 1} คือ ${a[i]} เรียบร้อย`);
    }

    // ตัวสุดท้ายที่เหลือ (index n - 1) อยู่ในตำแหน่งถูกต้องโดยอัตโนมัติ
    sorted.push(n - 1);
    yield makeStep('sorted', n - 1, n - 1, a, sorted,
      `ตำแหน่งสุดท้ายคือ ${a[n - 1]} เข้าที่โดยอัตโนมัติ`);

    const all = a.map((_, k) => k);
    yield makeStep('done', -1, -1, a, all, 'เรียงเสร็จแล้ว!');
  }

  /* ------------------------------------------------------------------------
     3) INSERTION SORT (การเรียงแบบแทรก) — โหมดห้องทดลอง
     ------------------------------------------------------------------------
     แนวคิด: เหมือนเรียงไพ่ในมือ ด้านซ้ายคือส่วนที่เรียงแล้ว
             หยิบตัวถัดไปมา แล้ว "เลื่อนไปทางซ้าย" จนเจอตำแหน่งที่เหมาะสม
             (ในที่นี้แสดงด้วยการสลับกับตัวซ้ายที่ใหญ่กว่าทีละขั้น)
     ความซับซ้อนเวลา: เฉลี่ย/แย่สุด O(n²), ดีสุด O(n) (เมื่อเกือบเรียงอยู่แล้ว)
  ------------------------------------------------------------------------ */
  function* insertionSort(input) {
    const a = input.slice();
    const n = a.length;

    for (let i = 1; i < n; i++) {
      // ส่วนที่เรียงแล้ว (ก่อนหยิบตัวใหม่) คือ index 0..i-1
      const prefix = Array.from({ length: i }, (_, k) => k);
      let j = i;                             // ตำแหน่งปัจจุบันของตัวที่กำลังแทรก

      while (j > 0) {
        yield makeStep('compare', j - 1, j, a, prefix,
          `เทียบ ${a[j - 1]} กับ ${a[j]} (ตัวที่กำลังแทรก)`);
        if (a[j - 1] > a[j]) {               // ตัวซ้ายใหญ่กว่า -> เลื่อนตัวที่แทรกไปซ้าย
          const leftVal = a[j - 1];
          const rightVal = a[j];
          [a[j - 1], a[j]] = [a[j], a[j - 1]];
          yield makeStep('swap', j - 1, j, a, prefix,
            `${leftVal} > ${rightVal} จึงเลื่อนตัวที่แทรกไปทางซ้าย`);
          j--;
        } else {
          break;                             // เจอตำแหน่งที่เหมาะสมแล้ว หยุดเลื่อน
        }
      }

      const upto = Array.from({ length: i + 1 }, (_, k) => k);
      yield makeStep('sorted', j, j, a, upto,
        `แทรก ${a[j]} เข้าที่แล้ว ส่วนซ้ายยาว ${i + 1} ตัวเรียงเรียบร้อย`);
    }

    const all = a.map((_, k) => k);
    yield makeStep('done', -1, -1, a, all, 'เรียงเสร็จแล้ว!');
  }

  /* ตารางชื่ออัลกอริทึม + คำอธิบายสั้น ๆ สำหรับแสดงในเกม */
  const INFO = {
    bubble: {
      name: 'Bubble Sort', fn: bubbleSort,
      desc: 'เทียบเฉพาะคู่ที่ติดกัน ถ้าซ้ายมากกว่าขวาให้สลับ ตัวมากสุดจะลอยไปท้ายแถวทีละรอบ',
      best: 'O(n)', avg: 'O(n²)', worst: 'O(n²)', swaps: 'ได้ถึง O(n²) ครั้ง'
    },
    selection: {
      name: 'Selection Sort', fn: selectionSort,
      desc: 'กวาดหาตัวที่น้อยที่สุดในส่วนที่ยังไม่เรียง แล้วสลับมาไว้หน้าสุด (สลับน้อยครั้งมาก)',
      best: 'O(n²)', avg: 'O(n²)', worst: 'O(n²)', swaps: 'ไม่เกิน n−1 ครั้ง'
    },
    insertion: {
      name: 'Insertion Sort', fn: insertionSort,
      desc: 'หยิบทีละตัวไปแทรกในส่วนซ้ายที่เรียงแล้ว เหมือนเรียงไพ่ในมือ',
      best: 'O(n)', avg: 'O(n²)', worst: 'O(n²)', swaps: 'ได้ถึง O(n²) ครั้ง'
    }
  };

  /* คู่มือนักสำรวจ: 3 ขั้นตอนการเรียนรู้ของแต่ละอัลกอริทึม (แสดงในหน้าเว็บ) */
  const GUIDE = {
    bubble: ['มองทีละคู่', 'เทียบตัวเลข', 'ทำซ้ำจนสุดแถว'],
    selection: ['กำหนดจุดเริ่ม', 'สแกนหาตัวน้อย', 'สลับเข้าตำแหน่ง']
  };

  /* โค้ดสำหรับแสดงใน Algorithm Lab: แต่ละบรรทัดมี { t: ข้อความ, hl: true ถ้าเป็นเงื่อนไขเปรียบเทียบหลัก }
     (เป็นเวอร์ชันอ่านง่ายของฟังก์ชันจริงด้านบน เน้นให้เห็นแนวคิด) */
  const CODE = {
    bubble: [
      { t: 'function bubbleSort(arr) {' },
      { t: '  const n = arr.length;' },
      { t: '  // รอบนอก: แต่ละรอบจะดันตัวมากสุดไปท้ายแถว 1 ตัว' },
      { t: '  for (let pass = 0; pass < n - 1; pass++) {' },
      { t: '    // รอบใน: มองทีละคู่ที่อยู่ติดกัน (ไม่ต้องดูส่วนท้ายที่ล็อกแล้ว)' },
      { t: '    for (let j = 0; j < n - 1 - pass; j++) {' },
      { t: '      // เงื่อนไขหลัก: ถ้าตัวซ้ายมากกว่าตัวขวา แปลว่าอยู่ผิดที่', hl: true },
      { t: '      if (arr[j] > arr[j + 1]) {', hl: true },
      { t: '        // สลับตำแหน่งของสองตัวนี้' },
      { t: '        [arr[j], arr[j + 1]] = [arr[j + 1], arr[j]];' },
      { t: '      }' },
      { t: '    }' },
      { t: '  }' },
      { t: '  return arr; // เรียงจากน้อยไปมากเรียบร้อย' },
      { t: '}' }
    ],
    selection: [
      { t: 'function selectionSort(arr) {' },
      { t: '  const n = arr.length;' },
      { t: '  // i คือจุดเริ่มของส่วนที่ "ยังไม่เรียง"' },
      { t: '  for (let i = 0; i < n - 1; i++) {' },
      { t: '    let min = i; // สมมติว่าตัวแรกของส่วนที่เหลือน้อยที่สุด' },
      { t: '    // สแกนส่วนที่เหลือเพื่อหาตัวที่น้อยกว่า' },
      { t: '    for (let j = i + 1; j < n; j++) {' },
      { t: '      // เงื่อนไขหลัก: เจอตัวที่น้อยกว่าค่าน้อยสุดตอนนี้ ให้จดตำแหน่งไว้', hl: true },
      { t: '      if (arr[j] < arr[min]) {', hl: true },
      { t: '        min = j;' },
      { t: '      }' },
      { t: '    }' },
      { t: '    // สลับตัวน้อยสุดเข้ามาไว้ตำแหน่ง i (สลับแค่ 1 ครั้งต่อรอบ)' },
      { t: '    if (min !== i) {' },
      { t: '      [arr[i], arr[min]] = [arr[min], arr[i]];' },
      { t: '    }' },
      { t: '  }' },
      { t: '  return arr; // เรียงจากน้อยไปมากเรียบร้อย' },
      { t: '}' }
    ]
  };

  /* ฟังก์ชันสะดวกใช้: คืน generator ของอัลกอริทึมตามชื่อ */
  function steps(name, arr) { return INFO[name].fn(arr); }

  /* ฟังก์ชันตรวจว่าเรียงจากน้อยไปมากแล้วหรือยัง */
  function isSorted(a) {
    for (let k = 1; k < a.length; k++) if (a[k - 1] > a[k]) return false;
    return true;
  }

  return { INFO, GUIDE, CODE, steps, isSorted, bubbleSort, selectionSort, insertionSort };
})();
